import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Force production mode to avoid dev warnings in SSR HTML
process.env.NODE_ENV = process.env.NODE_ENV || 'production';

// Toggle whether to emit per-route head debug files into dist/client/__debug_heads__
// Default: off in all builds unless explicitly enabled
const DEBUG_HEADS =
  String(process.env.GENERATE_DEBUG_HEADS || '').trim() === '1' ||
  process.argv.includes('--debug-heads');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const distClient = path.resolve(root, 'dist/client');
const distServer = path.resolve(root, 'dist/server');

async function main() {
  const serverEntry = path.join(distServer, 'entry-server.js');
  const hasServerEntry = fs.existsSync(serverEntry);
  if (!hasServerEntry) {
    console.warn('⚠️  Server entry not found. Falling back to client template replication without SSR.');
  }

  // Import using file protocol for Windows compatibility
  const render = hasServerEntry
    ? (await import(`file://${serverEntry}`)).render
    : null;

  let templatePath = path.join(distClient, 'index.html');
  if (!fs.existsSync(templatePath)) {
    const fallbackDist = path.join(root, 'dist', 'index.html');
    if (fs.existsSync(fallbackDist)) {
      templatePath = fallbackDist;
      console.warn(`⚠️  Using fallback client template (dist): ${templatePath}`);
    } else {
      const fallbackRoot = path.join(root, 'index.html');
      if (fs.existsSync(fallbackRoot)) {
        templatePath = fallbackRoot;
        console.warn(`⚠️  Using fallback client template (project root): ${templatePath}`);
      } else {
        console.error('Client template not found. Ensure build outputs or root index.html exist.');
        process.exit(1);
      }
    }
  }
  const template = fs.readFileSync(templatePath, 'utf-8');
  
  // Extract scripts and styles from client index.html to inject into SSR head
  // We want to capture <link rel="stylesheet"> and <script> tags
  // Specifically the ones generated by Vite (with assets path)
  const headAssets = extractHeadAssets(template);
  console.log(`Extracted head assets length: ${headAssets.length}`);

  const routesPath = path.join(root, 'prerender-routes.json');
  if (!fs.existsSync(routesPath)) {
    console.error('prerender-routes.json not found. Run node scripts/generate-prerender-routes.js first.');
    process.exit(1);
  }
  const routes = JSON.parse(fs.readFileSync(routesPath, 'utf-8'));

  console.log(`Generating static files for ${routes.length} routes...`);

  const report = [];
  for (const url of routes) {
    try {
      console.log(`Rendering ${url}...`);
      
      // Build final HTML by injecting SSR head & body into the client template
      let finalHtml = template;
      let dehydratedRouter = {};
      if (render) {
        const result = await render(url, headAssets);
        const headHtml = String(result?.headHtml || '');
        const bodyHtml = String(result?.bodyHtml || '');
        const locale = String(result?.locale || 'en');
        dehydratedRouter = result?.dehydratedRouter || {};

        // Inject lang attribute
        if (finalHtml.includes('<html')) {
          finalHtml = finalHtml.replace(
            /<html\b([^>]*)>/i,
            (m, attrs) => {
              let a = attrs || '';
              if (/lang\s*=/i.test(a)) {
                a = a.replace(/lang\s*=\s*["'][^"']*["']/i, `lang="${locale}"`);
              } else {
                a = `${a} lang="${locale}"`.trim();
              }
              return `<html ${a}>`.replace(/\s+>/, '>');
            }
          );
        }

        // Inject SSR head only (do NOT re-inject client assets to avoid duplicates)
        finalHtml = finalHtml.replace('</head>', `${headHtml}\n</head>`);

        // Inject app HTML into root
        finalHtml = finalHtml.replace(
          /<div id="root"><\/div>/,
          `<div id="root">${bodyHtml}</div>`
        );

        // Optional debug: write per-route headHtml to inspect SSR head output
        if (DEBUG_HEADS) {
          try {
            const debugDir = path.join(distClient, '__debug_heads__');
            if (!fs.existsSync(debugDir)) fs.mkdirSync(debugDir, { recursive: true });
            const safe = url === '/' ? 'root' : url.replace(/^\//, '').replace(/[\\\/]/g, '__');
            fs.writeFileSync(path.join(debugDir, `${safe}.head.html`), headHtml || '');
          } catch {}
        }
      }
      
      console.log(`- Final HTML length: ${finalHtml.length}`);
      
      // Collect SEO indicators for report
      try {
        const hasTitle = /<title>[\s\S]*?<\/title>/i.test(finalHtml);
        const metaDescMatch = finalHtml.match(/<meta\s+name=["']description["'][^>]*content=["']([^"']*)["'][^>]*>/i);
        const hasNonEmptyDescription = Boolean(metaDescMatch && String(metaDescMatch[1] || '').trim().length > 0);
        const hasCanonical = /<link\s+rel=["']canonical["'][^>]*>/i.test(finalHtml);
        const canonicalMatch = finalHtml.match(/<link\s+rel=["']canonical["']\s+href=["']([^"']+)["'][^>]*>/i);
        const alternates = [...finalHtml.matchAll(/<link\s+rel=["']alternate["'][^>]*hreflang=["']([^"']+)["'][^>]*href=["']([^"']+)["'][^>]*>/gi)].map(m => ({ hreflang: m[1], href: m[2] }));
        const urlPathOnly = String(url || '/').split('?')[0].split('#')[0];
        report.push({
          url: urlPathOnly,
          ssr: Boolean(render),
          htmlLength: finalHtml.length,
          hasTitle,
          hasMetaDescription: hasNonEmptyDescription,
          hasCanonical,
          canonical: canonicalMatch ? canonicalMatch[1] : null,
          alternates
        });
      } catch {}

      // Do not inject fallback H1 at build time; content SEO is handled by SSR/routes

      // Inject dehydrated state
      const dehydratedScript = `<script>window.__TANSTACK_ROUTER_CONTEXT__ = ${JSON.stringify(dehydratedRouter)}</script>`;
      if (!finalHtml.includes('__TANSTACK_ROUTER_CONTEXT__')) {
        if (finalHtml.includes('<head>')) {
          finalHtml = finalHtml.replace('<head>', `<head>${dehydratedScript}`);
        } else {
          finalHtml = finalHtml.replace('</body>', `${dehydratedScript}</body>`);
        }
      }
      
      const filePath = url === '/' 
        ? 'index.html' 
        : path.join(url.substring(1), 'index.html');
        
      const fullPath = path.join(distClient, filePath);
      const dir = path.dirname(fullPath);
      
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      
      fs.writeFileSync(fullPath, finalHtml);
    } catch (e) {
      console.error(`Error generating ${url}:`, e);
      report.push({
        url,
        ssr: Boolean(render),
        error: String(e?.message || e) || 'Unknown error'
      });
    }
  }

  try {
    const outPath = path.join(distClient, 'prerender-report.json');
    const summary = {
      generatedAt: new Date().toISOString(),
      total: report.length,
      success: report.filter(r => !r.error).length,
      fail: report.filter(r => r.error).length,
      pages: report
    };
    if (!fs.existsSync(distClient)) fs.mkdirSync(distClient, { recursive: true });
    fs.writeFileSync(outPath, JSON.stringify(summary, null, 2));
    console.log(`📝 Prerender report written: ${outPath}`);
  } catch (err) {
    console.warn('⚠️  Failed to write prerender-report.json:', err?.message || err);
  }
  console.log('Static generation complete.');
}

function extractHeadAssets(html) {
  // Simple regex to extract css links and scripts from the built index.html
  // We look for:
  // <link rel="stylesheet" ...>
  // <script type="module" ...>
  // <link rel="modulepreload" ...>
  
  const assets = [];
  
  // Match CSS links
  const cssRegex = /<link[^>]+rel="stylesheet"[^>]*>/g;
  const cssMatches = html.match(cssRegex);
  if (cssMatches) assets.push(...cssMatches);
  
  // Match Module Scripts (entry point) - only include built assets, skip dev /src/*
  const scriptRegex = /<script[^>]+type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g;
  const scriptMatches = [...html.matchAll(scriptRegex)]
    .map(m => ({ tag: m[0], src: m[1] }))
    .filter(m => m.src.includes('/assets/'))
    .map(m => m.tag);
  if (scriptMatches.length) assets.push(...scriptMatches);

  // Match Module Preload
  const preloadRegex = /<link[^>]+rel="modulepreload"[^>]*>/g;
  const preloadMatches = html.match(preloadRegex);
  if (preloadMatches) assets.push(...preloadMatches);

  return assets.join('\n');
}

// Ensure the Node process exits cleanly so that chained build commands continue
main()
  .then(() => {
    process.exit(0);
  })
  .catch(err => {
    console.error(err);
    process.exit(1);
  });
